#!/usr/bin/env python3
"""Rebuild every SEVERANCE asset headless and deterministically.

    python3 blender/build_all.py                       # everything
    python3 blender/build_all.py --only chassis,kkv    # a subset (kits reuse the cached chassis scene)
    python3 blender/build_all.py --no-preview          # skip the Cycles preview renders

Writes assets/*.glb, assets/tex/*, assets/previews/<asset>.png and js/data/hull_layout.json (merged:
entries for assets not rebuilt in this run are kept).
"""
import argparse
import importlib
import json
import os
import sys
import time

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
sys.path.insert(0, HERE)

import bpy  # noqa: E402
from lib import core, masks, export, render  # noqa: E402

ASSET_DIR = os.path.join(ROOT, 'assets')
PREVIEW_DIR = os.path.join(ASSET_DIR, 'previews')
CACHE = os.path.join(HERE, '.cache')
LAYOUT_PATH = os.path.join(ROOT, 'js', 'data', 'hull_layout.json')
LAYOUT_ASSETS = ['chassis', 'kit_recon', 'kit_skirmisher', 'kit_picket', 'gunship', 'hauler', 'depot', 'decoy', 'kkv']

# asset -> (module, function). Order = build order (kits need the chassis scene cached first).
REG = {
    'textures': ('textures', 'main'),
    'chassis': ('interceptor', 'build_chassis'),
    'kit_recon': ('interceptor', 'build_kit_recon'),
    'kit_skirmisher': ('interceptor', 'build_kit_skirmisher'),
    'kit_picket': ('interceptor', 'build_kit_picket'),
    'cockpit': ('cockpit', 'build'),
    'pilot': ('pilot', 'build'),
    'kkv': ('kkv', 'build'),
    'gunship': ('gunship', 'build'),
    'debris': ('debris', 'build'),
    'depot': ('depot', 'build'),
    'hauler': ('hauler', 'build'),
    'decoy': ('decoy', 'build'),
}


def build_asset(name, preview=True):
    modname, fn = REG[name]
    mod = importlib.import_module(modname)
    t0 = time.time()
    base = set()
    chassis_blend = os.path.join(CACHE, 'chassis.blend')
    if name.startswith('kit_'):
        if not os.path.exists(chassis_blend):
            build_asset('chassis', preview=False)
        bpy.ops.wm.open_mainfile(filepath=chassis_blend)
        base = set(bpy.context.scene.objects)
    else:
        core.reset()
    info = getattr(mod, fn)() or {}
    t1 = time.time()
    own = [o for o in bpy.context.scene.objects if o not in base]
    core.finalize([o for o in own if o.type == 'MESH'])
    own = [o for o in bpy.context.scene.objects if o not in base]
    own_mesh = [o for o in own if o.type == 'MESH']
    m = dict(info.get('masks', {}))
    occl = [o for o in core.mesh_objects() if not o.name.startswith('DECAL_')]
    masks.bake(objs=own_mesh, occluders=occl, **m)
    t2 = time.time()
    if name == 'chassis':
        os.makedirs(CACHE, exist_ok=True)
        bpy.ops.wm.save_as_mainfile(filepath=chassis_blend, compress=False)
    lay = None
    if name in LAYOUT_ASSETS:
        lay = export.layout(root=info.get('root'), objs=own)
    out = os.path.join(ASSET_DIR, name + '.glb')
    export.export_glb(out, cameras=info.get('cameras', False), objects=own if base else None)
    tris = core.tri_count(own_mesh)
    t3 = time.time()
    if preview:
        pv = dict(info.get('preview', {}))
        cam = pv.pop('camera', None)
        if cam:
            c = render.camera_at(cam['loc'], cam['target'], cam.get('fov', 60))
            render.sun(pv.get('sun_dir', (-0.55, 0.75, 0.9)), pv.get('energy', 5.0))
            render.render(os.path.join(PREVIEW_DIR, name + '.png'), c, pv.get('samples', 24))
        else:
            render.preview(os.path.join(PREVIEW_DIR, name + '.png'), **pv)
    t4 = time.time()
    size = os.path.getsize(out)
    print(f'[{name}] tris={tris} size={size / 1024:.0f}KiB build={t1 - t0:.1f}s masks={t2 - t1:.1f}s '
          f'export={t3 - t2:.1f}s preview={t4 - t3:.1f}s', flush=True)
    return lay, tris, size


def write_layout(updates):
    data = {}
    if os.path.exists(LAYOUT_PATH):
        with open(LAYOUT_PATH) as f:
            data = json.load(f)
    data['_note'] = ('GENERATED by blender/build_all.py from the HIT_* and anchor empties of the built scenes '
                     '(Blender root frame, metres; hit c = centre, h = half extents; anchor q = [w,x,y,z]). '
                     'Do not edit by hand.')
    for k, v in updates.items():
        data[k] = v
    ordered = {'_note': data['_note']}
    for k in LAYOUT_ASSETS:
        if k in data:
            ordered[k] = data[k]
    with open(LAYOUT_PATH, 'w') as f:
        json.dump(ordered, f, indent=1)
        f.write('\n')


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--only', default='')
    ap.add_argument('--no-preview', action='store_true')
    args = ap.parse_args([a for a in sys.argv[1:] if a != '--'])
    names = [n for n in REG if not args.only or n in args.only.split(',')]
    os.makedirs(PREVIEW_DIR, exist_ok=True)
    os.makedirs(os.path.join(ASSET_DIR, 'tex'), exist_ok=True)
    updates, summary = {}, []
    for n in names:
        if n == 'textures':
            t0 = time.time()
            importlib.import_module('textures').main(os.path.join(ASSET_DIR, 'tex'))
            print(f'[textures] {time.time() - t0:.1f}s', flush=True)
            continue
        lay, tris, size = build_asset(n, preview=not args.no_preview)
        summary.append((n, tris, size))
        if lay is not None:
            updates[n] = lay
    if updates:
        write_layout(updates)
    print('\nasset            tris      KiB')
    for n, t, s in summary:
        print(f'{n:15s} {t:7d} {s / 1024:8.0f}')


if __name__ == '__main__':
    main()
